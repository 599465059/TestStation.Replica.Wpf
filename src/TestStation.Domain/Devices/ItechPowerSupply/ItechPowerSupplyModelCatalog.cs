    public static List<PowerSupplyModel> CreateModels()
    {
        var models = new List<PowerSupplyModel>
        {
            new() { Id = "public-scpi", Name = "公共 SCPI 模拟配置", MaxVoltage = 60, MaxCurrent = 10, MaxPower = 600 },
        };
        foreach (var rating in Ratings)
        {
            models.Add(new PowerSupplyModel
            {
                Id = rating.Model,
                Name = $"ITECH {rating.Model}",
                MaxVoltage = rating.Voltage,
                MaxCurrent = rating.Current,
                MaxPower = rating.Power,
                Bidirectional = rating.Family is "IT6000B" or "IT6000C" or "IT6000D" || rating.Model.Contains('B', StringComparison.OrdinalIgnoreCase),
                Photovoltaic = rating.Family == "IT6000PV",
                DriverId = "itech.public-scpi",
                ProtocolId = "scpi"
            });
        }
        return models;
    }
